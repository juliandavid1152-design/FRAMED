        CONSTRAINT PK_TIPO_ESTABLECIMIENTO PRIMARY KEY,
    NOMBRE VARCHAR2(100)
        CONSTRAINT NN_TIPO_ESTABLECIMIENTO_NOMBRE NOT NULL,
    CONSTRAINT UK_TIPO_ESTABLECIMIENTO_NOMBRE UNIQUE (NOMBRE)
);


/* =========================================================
