/* =========================================================
   1. TABLA MUNICIPIOS
   ========================================================= */

CREATE TABLE MUNICIPIOS (
    CODIGO_MUNICIPIO NUMBER(3) CONSTRAINT PK_MUNICIPIOS PRIMARY KEY,
    NOMBRE           VARCHAR2(60) CONSTRAINT NN_MUNICIPIOS_NOMBRE NOT NULL,
    CONSTRAINT UK_MUNICIPIOS_NOMBRE UNIQUE (NOMBRE)
);


/* =========================================================
   2. TABLA TIPO_ESTABLECIMIENTO
   ========================================================= */

CREATE TABLE TIPO_ESTABLECIMIENTO (
