        CONSTRAINT PK_ESTADOS_ESTABLECIMIENTO PRIMARY KEY,
    NOMBRE VARCHAR2(30)
        CONSTRAINT NN_ESTADOS_NOMBRE NOT NULL,
    CONSTRAINT UK_ESTADOS_NOMBRE UNIQUE (NOMBRE)
);


/* =========================================================
   5. TABLA GRUPOS_ESTABLECIMIENTO
   ========================================================= */

CREATE TABLE GRUPOS_ESTABLECIMIENTO (

    CODIGO_GRUPO NUMBER(1)
        CONSTRAINT PK_GRUPOS_ESTABLECIMIENTO PRIMARY KEY,

    NOMBRE VARCHAR2(20)
        CONSTRAINT NN_GRUPOS_NOMBRE NOT NULL,

    CONSTRAINT UK_GRUPOS_NOMBRE UNIQUE (NOMBRE)

);


/* =========================================================
   6. TABLA TITULOS_DIRECTOR_TECNICO
   ========================================================= */

CREATE TABLE TITULOS_DIRECTOR_TECNICO (

    CODIGO_TITULO NUMBER(2)
        CONSTRAINT PK_TITULOS_DIRECTOR PRIMARY KEY,

    NOMBRE VARCHAR2(120)
        CONSTRAINT NN_TITULOS_DIRECTOR_NOMBRE NOT NULL,

    CONSTRAINT UK_TITULOS_DIRECTOR_NOMBRE UNIQUE (NOMBRE)

);


/* =========================================================
   7. TABLA TIPOS_NOVEDAD
   ========================================================= */

CREATE TABLE TIPOS_NOVEDAD (
    ID_TIPO_NOVEDAD      NUMBER GENERATED BY DEFAULT AS IDENTITY
                         PRIMARY KEY,
    CODIGO               NUMBER(2) NOT NULL,
    TIPO_NOVEDAD         VARCHAR2(200) NOT NULL,
    ACTUALIZA_CENSO      CHAR(1) DEFAULT 'N'
                         CHECK (ACTUALIZA_CENSO IN ('S','N')),
    ACTIVO               CHAR(1) DEFAULT 'S'
                         CHECK (ACTIVO IN ('S','N'))
);


/* =========================================================
   8. TABLA ESTADOS_REPORTE
   ========================================================= */

CREATE TABLE ESTADOS_REPORTE (
    ID_ESTADO_REPORTE    NUMBER GENERATED BY DEFAULT AS IDENTITY
                         PRIMARY KEY,
    NOMBRE_ESTADO        VARCHAR2(50) NOT NULL,
    DESCRIPCION          VARCHAR2(300),
    ACTIVO               CHAR(1) DEFAULT 'S'
                         CHECK (ACTIVO IN ('S','N'))
);


/* =========================================================
   9. TABLA CAMPOS_NOVEDAD
   ========================================================= */

CREATE TABLE CAMPOS_NOVEDAD (

    ID_CAMPO NUMBER GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_CAMPOS_NOVEDAD PRIMARY KEY,

    ETIQUETA VARCHAR2(100)
        CONSTRAINT NN_CAMPOS_NOVEDAD_ETIQUETA NOT NULL,

    TIPO_DATO VARCHAR2(20)
        CONSTRAINT NN_CAMPOS_NOVEDAD_TIPO NOT NULL
        CONSTRAINT CK_CAMPOS_NOVEDAD_TIPO
        CHECK (TIPO_DATO IN (
            'TEXTO',
            'TEXTO_LARGO',
            'NUMERO',
            'FECHA',
            'EMAIL',
            'TELEFONO',
            'LISTA'
        )),

    ACTIVO CHAR(1) DEFAULT 'S'
        CONSTRAINT CK_CAMPOS_NOVEDAD_ACTIVO
        CHECK (ACTIVO IN ('S','N')),

    CONSTRAINT UK_CAMPOS_NOVEDAD_ETIQUETA
        UNIQUE (ETIQUETA)

);


/* =========================================================
   10. TABLA SERVICIOS
   ========================================================= */

CREATE TABLE SERVICIOS (

    CODIGO_SERVICIO NUMBER(2)
        CONSTRAINT PK_SERVICIOS PRIMARY KEY,

    NOMBRE VARCHAR2(100)
        CONSTRAINT NN_SERVICIOS_NOMBRE NOT NULL,

    CAMPO_CENSO VARCHAR2(30)
        CONSTRAINT NN_SERVICIOS_COLUMNA NOT NULL,

    ACTIVO CHAR(1) DEFAULT 'S'
        CONSTRAINT CK_SERVICIOS_ACTIVO
        CHECK (ACTIVO IN ('S','N')),

    CONSTRAINT UK_SERVICIOS_NOMBRE
        UNIQUE (NOMBRE),

    CONSTRAINT UK_SERVICIOS_COLUMNA
        UNIQUE (CAMPO_CENSO)

);


/* =========================================================
   11. TABLA TIPOS_REPORTANTE
   ========================================================= */

CREATE TABLE TIPOS_REPORTANTE (

    CODIGO_TIPO_REPORTANTE NUMBER(1)
        CONSTRAINT PK_TIPOS_REPORTANTE PRIMARY KEY,

    NOMBRE VARCHAR2(50)
        CONSTRAINT NN_TIPOS_REPORTANTE_NOMBRE NOT NULL,

    CONSTRAINT UK_TIPOS_REPORTANTE_NOMBRE
        UNIQUE (NOMBRE)

);


/* =========================================================
   12. TABLA CONCEPTOS_SANITARIOS
   ========================================================= */

CREATE TABLE CONCEPTOS_SANITARIOS (

    CODIGO_CONCEPTO_SANITARIO NUMBER(1)
        CONSTRAINT PK_CONCEPTOS_SANITARIOS PRIMARY KEY,

    NOMBRE VARCHAR2(50)
        CONSTRAINT NN_CONCEPTOS_SANITARIOS_NOMBRE NOT NULL,

    CONSTRAINT UK_CONCEPTOS_SANITARIOS_NOMBRE
        UNIQUE (NOMBRE)

);


/* =========================================================
   13. TABLA TITULO_TIPO_ESTABLECIMIENTO
   ========================================================= */

CREATE TABLE TITULO_TIPO_ESTABLECIMIENTO (

    CODIGO_TIPO_ESTABLECIMIENTO NUMBER(2)
        CONSTRAINT FK_TTE_TIPO
        REFERENCES TIPO_ESTABLECIMIENTO(CODIGO_TIPO_ESTABLECIMIENTO),

    CODIGO_TITULO NUMBER(2)
        CONSTRAINT FK_TTE_TITULO
        REFERENCES TITULOS_DIRECTOR_TECNICO(CODIGO_TITULO),

    CONSTRAINT PK_TITULO_TIPO_ESTABLECIMIENTO
        PRIMARY KEY (CODIGO_TIPO_ESTABLECIMIENTO, CODIGO_TITULO)

);


/* =========================================================
   14. TABLA ESTABLECIMIENTOS
   ========================================================= */

CREATE TABLE ESTABLECIMIENTOS (

    CODIGO_ESTABLECIMIENTO VARCHAR2(20)
        CONSTRAINT PK_ESTABLECIMIENTOS PRIMARY KEY,

    CODIGO_GRUPO NUMBER(1)
        CONSTRAINT FK_EST_GRUPO
        REFERENCES GRUPOS_ESTABLECIMIENTO (CODIGO_GRUPO),

    CODIGO_TIPO_ESTABLECIMIENTO NUMBER(2)
        CONSTRAINT FK_EST_TIPO
        REFERENCES TIPO_ESTABLECIMIENTO (CODIGO_TIPO_ESTABLECIMIENTO),

    CODIGO_REGION NUMBER(2)
        CONSTRAINT FK_EST_REGION
        REFERENCES REGIONES (CODIGO_REGION),

    CODIGO_MUNICIPIO NUMBER(3)
        CONSTRAINT FK_EST_MUNICIPIO
        REFERENCES MUNICIPIOS (CODIGO_MUNICIPIO),

    RAZON_SOCIAL VARCHAR2(200)
        CONSTRAINT NN_EST_RAZON_SOCIAL NOT NULL,

    DIRECCION VARCHAR2(250),

    BARRIO VARCHAR2(100),

    TELEFONOS VARCHAR2(200),

    ID_DT VARCHAR2(20),

    NOMBRE_DIRECTOR_TECNICO VARCHAR2(200),

    CODIGO_TITULO NUMBER(2)
        CONSTRAINT FK_EST_TITULO_DT
        REFERENCES TITULOS_DIRECTOR_TECNICO (CODIGO_TITULO),

    ID_PROPIETARIO VARCHAR2(20),

    NOMBRE_PROPIETARIO VARCHAR2(200),

    ID_RL VARCHAR2(20),

    NOMBRE_REPRESENTANTE VARCHAR2(200),

    MATRICULA_MERCANTIL VARCHAR2(30),

    NIT VARCHAR2(20)
        CONSTRAINT UK_EST_NIT UNIQUE,

    EMAIL VARCHAR2(150)
        CONSTRAINT CK_EST_EMAIL
        CHECK (EMAIL IS NULL OR EMAIL LIKE '%@%.%'),

    CODIGO_ESTADO NUMBER(1)
        CONSTRAINT FK_EST_ESTADO
        REFERENCES ESTADOS_ESTABLECIMIENTO (CODIGO_ESTADO),

    FECHA_CREACION DATE DEFAULT SYSDATE,

    USUARIO_CREACION VARCHAR2(50),

    FECHA_ULTIMA_ACTUALIZACION DATE DEFAULT SYSDATE,

    USUARIO_ULTIMA_ACTUALIZACION VARCHAR2(50),

    ID_ULTIMA_NOVEDAD NUMBER,

    OBSERVACIONES VARCHAR2(500)

);


/* =========================================================
   15. TABLA TIPO_NOVEDAD_ESTABLECIMIENTO
   ========================================================= */

CREATE TABLE TIPO_NOVEDAD_ESTABLECIMIENTO (
    ID_TIPO_NOVEDAD_ESTABLECIMIENTO NUMBER GENERATED BY DEFAULT AS IDENTITY
                                    PRIMARY KEY,

    ID_TIPO_NOVEDAD                 NUMBER NOT NULL,

    CODIGO_TIPO_ESTABLECIMIENTO     NUMBER(2) NOT NULL,

    CONSTRAINT FK_TNE_TIPO_NOVEDAD
        FOREIGN KEY (ID_TIPO_NOVEDAD)
        REFERENCES TIPOS_NOVEDAD(ID_TIPO_NOVEDAD),

    CONSTRAINT FK_TNE_TIPO_ESTABLECIMIENTO
        FOREIGN KEY (CODIGO_TIPO_ESTABLECIMIENTO)
        REFERENCES TIPO_ESTABLECIMIENTO(CODIGO_TIPO_ESTABLECIMIENTO),

    CONSTRAINT UK_TNE
        UNIQUE (
            ID_TIPO_NOVEDAD,
            CODIGO_TIPO_ESTABLECIMIENTO
        )
);


/* =========================================================
   16. TABLA TIPO_NOVEDAD_CAMPOS
   ========================================================= */

CREATE TABLE TIPO_NOVEDAD_CAMPOS (
    ID_TIPO_NOVEDAD_CAMPO  NUMBER GENERATED BY DEFAULT AS IDENTITY
                           PRIMARY KEY,

    ID_TIPO_NOVEDAD        NUMBER NOT NULL,

    ID_CAMPO               NUMBER NOT NULL,

    OBLIGATORIO            CHAR(1) DEFAULT 'N'
                           CHECK (OBLIGATORIO IN ('S','N')),

    ACTUALIZA_CENSO        CHAR(1) DEFAULT 'N'
                           CHECK (ACTUALIZA_CENSO IN ('S','N')),

    ORDEN                  NUMBER(2) NOT NULL,

    CONSTRAINT FK_TNC_TIPO_NOVEDAD
        FOREIGN KEY (ID_TIPO_NOVEDAD)
        REFERENCES TIPOS_NOVEDAD (ID_TIPO_NOVEDAD),

    CONSTRAINT FK_TNC_CAMPO
        FOREIGN KEY (ID_CAMPO)
        REFERENCES CAMPOS_NOVEDAD (ID_CAMPO),

    CONSTRAINT UK_TNC
        UNIQUE (ID_TIPO_NOVEDAD, ID_CAMPO)
);


/* =========================================================
   17. TABLA REPORTES
   ========================================================= */

CREATE TABLE REPORTES (

    ID_REPORTE NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_REPORTES PRIMARY KEY,

    CODIGO_ESTABLECIMIENTO VARCHAR2(20)
        CONSTRAINT NN_REP_ESTABLECIMIENTO NOT NULL
        CONSTRAINT FK_REP_ESTABLECIMIENTO
            REFERENCES ESTABLECIMIENTOS (CODIGO_ESTABLECIMIENTO),

    ID_TIPO_NOVEDAD NUMBER
        CONSTRAINT NN_REP_TIPO_NOVEDAD NOT NULL
        CONSTRAINT FK_REP_TIPO_NOVEDAD
            REFERENCES TIPOS_NOVEDAD (ID_TIPO_NOVEDAD),

    ID_ESTADO_REPORTE NUMBER
        CONSTRAINT NN_REP_ESTADO NOT NULL
        CONSTRAINT FK_REP_ESTADO
            REFERENCES ESTADOS_REPORTE (ID_ESTADO_REPORTE),

    CODIGO_TIPO_REPORTANTE NUMBER(1)
        CONSTRAINT NN_REP_TIPO_REPORTANTE NOT NULL
        CONSTRAINT FK_REP_TIPO_REPORTANTE
            REFERENCES TIPOS_REPORTANTE (CODIGO_TIPO_REPORTANTE),

    NOMBRE_REPORTANTE VARCHAR2(200)
        CONSTRAINT NN_REP_NOMBRE_REPORTANTE NOT NULL,

    DOCUMENTO_REPORTANTE VARCHAR2(20)
        CONSTRAINT NN_REP_DOCUMENTO_REPORTANTE NOT NULL,

    FECHA_REPORTE DATE
        DEFAULT SYSDATE
        CONSTRAINT NN_REP_FECHA_REPORTE NOT NULL,

    FECHA_NOTIFICACION DATE,

    OBSERVACIONES VARCHAR2(1000)

);


/* =========================================================
   18. TABLA DETALLE_REPORTE
   ========================================================= */

CREATE TABLE DETALLE_REPORTE (

    ID_DETALLE_REPORTE NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_DETALLE_REPORTE PRIMARY KEY,

    ID_REPORTE NUMBER
        CONSTRAINT NN_DR_REPORTE NOT NULL
        CONSTRAINT FK_DR_REPORTE
            REFERENCES REPORTES (ID_REPORTE),

    ID_TIPO_NOVEDAD_CAMPO NUMBER
        CONSTRAINT NN_DR_CAMPO NOT NULL
        CONSTRAINT FK_DR_CAMPO
            REFERENCES TIPO_NOVEDAD_CAMPOS (ID_TIPO_NOVEDAD_CAMPO),

    VALOR VARCHAR2(4000)
        CONSTRAINT NN_DR_VALOR NOT NULL

);


/* =========================================================
   19. TABLA HISTORIAL_ACTUALIZACIONES
   ========================================================= */

CREATE TABLE HISTORIAL_ACTUALIZACIONES (

    ID_HISTORIAL NUMBER
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT PK_HISTORIAL_ACTUALIZACIONES PRIMARY KEY,

    ID_REPORTE NUMBER
        CONSTRAINT NN_HIST_REPORTE NOT NULL
        CONSTRAINT FK_HIST_REPORTE
            REFERENCES REPORTES (ID_REPORTE),

    CODIGO_ESTABLECIMIENTO VARCHAR2(20)
        CONSTRAINT NN_HIST_ESTABLECIMIENTO NOT NULL
        CONSTRAINT FK_HIST_ESTABLECIMIENTO
            REFERENCES ESTABLECIMIENTOS (CODIGO_ESTABLECIMIENTO),

    ID_CAMPO NUMBER
        CONSTRAINT NN_HIST_CAMPO NOT NULL
        CONSTRAINT FK_HIST_CAMPO
            REFERENCES CAMPOS_NOVEDAD (ID_CAMPO),

    VALOR_ANTERIOR VARCHAR2(4000),

    VALOR_NUEVO VARCHAR2(4000)
        CONSTRAINT NN_HIST_VALOR_NUEVO NOT NULL,

    FECHA_ACTUALIZACION DATE
        DEFAULT SYSDATE
        CONSTRAINT NN_HIST_FECHA NOT NULL

);


